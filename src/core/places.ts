const FLAT: Record<string, LonLat> = Object.assign({}, ...Object.values(PLACE_GROUPS));

/** 地名 → 经纬度；找不到返回 null */
export const lookupPlace = (p: Place): LonLat | null => {
  if (Array.isArray(p)) return p.length === 2 && p.every((v) => typeof v === 'number' && Number.isFinite(v)) ? [p[0], p[1]] : null;
  if (typeof p !== 'string') return null;
  const name = p.trim();
  return FLAT[name] ?? REGION_CENTERS[name] ?? (ALIASES[name] ? FLAT[ALIASES[name]] : null) ?? null;
};

/** 所有能用的地名（检查时给建议用） */
export const ALL_PLACE_NAMES = [...Object.keys(FLAT), ...Object.keys(REGION_CENTERS), ...Object.keys(ALIASES)];

/** 名字相近的地名（找不到时提示） */
export const similarPlaces = (name: string) => {
  const chars = new Set([...name]);
  return ALL_PLACE_NAMES.map((n) => ({n, score: [...n].filter((c) => chars.has(c)).length}))
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, 5)
    .map((x) => x.n);
};
